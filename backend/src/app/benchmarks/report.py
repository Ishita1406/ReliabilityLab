"""Generate the benchmark report from an actual execution (never from expectations).

    uv run python -m app.benchmarks.report --suite reliability-demo@1.0.0 \\
        --agents baseline,prompt-b,no-retry,single-source,slow-backoff --repetitions 2 \\
        --output ../docs/benchmarks/reliability-demo-1.0.0-report.md

Every number in the output comes from running the listed agent configurations through the
runner and evaluator in this process at generation time; the report records the command, the
git commit, and the time it was produced.
"""

import argparse
import platform
import subprocess
from collections import Counter
from datetime import datetime
from pathlib import Path

from app.domain.benchmark import BenchmarkSuite
from app.domain.hashing import content_sha256
from app.evaluation.engine import EVALUATOR_VERSION
from app.experiments.comparison import UnitStatus, compare
from app.experiments.metrics import ExperimentMetrics, MetricValue, compute_metrics
from app.experiments.records import ExperimentResults
from app.experiments.regression_check import AGENTS, _suite
from app.experiments.samples import run_sample_experiment, sample_configuration
from app.runner.runner import RUNNER_VERSION


def _git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        )
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "--", "."], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown (not a git checkout)"
    return out.stdout.strip() + (" + uncommitted changes" if dirty.stdout.strip() else "")


def fmt(metric: MetricValue) -> str:
    if metric.value is None:
        return f"n/a ({metric.unavailable_reason})"
    if metric.unit == "ratio":
        ci = (
            f" [{metric.ci_low:.1%}, {metric.ci_high:.1%}]"
            if metric.ci_low is not None and metric.ci_high is not None
            else ""
        )
        return f"{metric.value:.1%} ({metric.numerator}/{metric.denominator}){ci}"
    if metric.unit == "seconds":
        return f"{metric.value:.2f} s (n={metric.denominator})"
    return f"${metric.value:.4f} (known for {metric.numerator}/{metric.denominator})"


def _scenario_section(suite: BenchmarkSuite) -> list[str]:
    kinds = Counter(s.kind.value for s in suite.scenarios)
    faults = Counter(f.type.value for s in suite.scenarios for f in s.faults)
    lines = [
        "## Dataset",
        "",
        f"- Suite: `{suite.id}` version `{suite.version}` (schema {suite.schema_version}), "
        f"synthetic: {suite.synthetic}",
        f"- Content SHA-256: `{content_sha256(suite)}`",
        f"- Cases: {len(suite.cases)}; scenarios: {len(suite.scenarios)} "
        f"({', '.join(f'{n} {k}' for k, n in sorted(kinds.items()))})",
        f"- Injected fault types: {', '.join(f'{k} x{n}' for k, n in sorted(faults.items()))}",
        "",
        "| Case | Expected outcome | Scenarios | Tags |",
        "| --- | --- | --- | --- |",
    ]
    for case in suite.cases:
        names = [s.id.removeprefix(case.id + ".") for s in suite.scenarios_for(case.id)]
        lines.append(
            f"| `{case.id}` | {case.expectation.expected_behavior.outcome.value} | "
            f"{', '.join(names)} | {', '.join(case.tags)} |"
        )
    return lines


METRIC_ROWS = [
    ("Task success rate", "task_success_rate"),
    ("Fault recovery rate", "fault_recovery_rate"),
    ("Unauthorized-action rate", "unauthorized_action_rate"),
    ("Evaluator uncertainty rate", "evaluator_uncertainty_rate"),
    ("Latency mean (virtual clock)", "latency_mean"),
    ("Latency p95 (virtual clock)", "latency_p95"),
    ("Cost per run", "cost_per_run_mean"),
]


def render(
    suite: BenchmarkSuite, results: dict[str, ExperimentResults], repetitions: int, command: str
) -> str:
    metrics: dict[str, ExperimentMetrics] = {a: compute_metrics(r) for a, r in results.items()}
    agents = list(results)
    reference = agents[0]
    lines = [
        f"# Benchmark report: {suite.id} {suite.version}",
        "",
        "> Generated by `app.benchmarks.report` from an actual execution. Do not edit numbers by "
        "hand; regenerate instead.",
        "",
        f"- Generated: {datetime.now().astimezone().isoformat(timespec='seconds')}",
        f"- Git commit: {_git_commit()}",
        f"- Python {platform.python_version()} on {platform.system()} {platform.machine()}",
        f"- Command: `{command}`",
        "",
        *_scenario_section(suite),
        "",
        "## Evaluation protocol",
        "",
        f"- Runner `{RUNNER_VERSION}`, evaluator `evaluator-{EVALUATOR_VERSION}` (deterministic; "
        "no LLM judge). Scoring: weighted criteria with required criteria; per-scenario "
        "expectations as defined in the dataset (Milestone 6).",
        f"- Each agent configuration runs every scenario {repetitions} time(s) with seed 0 "
        "(derived per run), limits 40 steps / 12 tool calls / 120 s deadline (virtual clock).",
        "- Agent configurations are variants of the deterministic research agent (no language "
        "model): "
        + ", ".join(
            f"`{a}` ({AGENTS[a].model.name}, prompt label {AGENTS[a].version_label})"
            for a in agents
        )
        + ".",
        f"- Comparisons use `{reference}` as the baseline (Milestone 7 semantics: a scenario "
        "passes only if every repetition passes; exact McNemar test on scenarios).",
        "",
        "## Measured metrics",
        "",
        "Values with 95% Wilson intervals; denominators are runs (criteria for fault recovery).",
        "",
        "| Metric | " + " | ".join(f"`{a}`" for a in agents) + " |",
        "| --- |" + " --- |" * len(agents),
    ]
    for label, name in METRIC_ROWS:
        lines.append(
            f"| {label} | " + " | ".join(fmt(metrics[a].scalar(name)) for a in agents) + " |"
        )
    lines += ["", "### Failure labels (runs carrying the label)", ""]
    lines.append("| Label | " + " | ".join(f"`{a}`" for a in agents) + " |")
    lines.append("| --- |" + " --- |" * len(agents))
    labels = sorted(
        {
            label
            for m in metrics.values()
            for label, v in m.failure_rate.items()
            if (v.numerator or 0) > 0
        }
    )
    for label in labels:
        lines.append(
            f"| {label} | " + " | ".join(fmt(metrics[a].failure_rate[label]) for a in agents) + " |"
        )
    if not labels:
        lines.append("| (none) |" + " |" * len(agents))

    lines += ["", "### Verdict per scenario", ""]
    lines.append("| Scenario | " + " | ".join(f"`{a}`" for a in agents) + " |")
    lines.append("| --- |" + " --- |" * len(agents))
    for scenario in suite.scenarios:
        cells = []
        for agent in agents:
            verdicts = Counter(
                r.evaluation.verdict.value
                for r in results[agent].for_scenario(scenario.id)
                if r.evaluation is not None
            )
            cells.append(", ".join(f"{v} x{n}" for v, n in sorted(verdicts.items())) or "not run")
        lines.append(f"| `{scenario.id}` | " + " | ".join(cells) + " |")

    lines += ["", f"## Comparisons against `{reference}`", ""]
    lines.append("| Candidate | Newly failing | Newly passing | Not comparable | Paired test |")
    lines.append("| --- | --- | --- | --- | --- |")
    for agent in agents[1:]:
        comparison = compare(results[reference], results[agent])
        failing = [u.scenario_id for u in comparison.by_status(UnitStatus.NEWLY_FAILING)]
        passing = [u.scenario_id for u in comparison.by_status(UnitStatus.NEWLY_PASSING)]
        paired = comparison.paired_test
        lines.append(
            f"| `{agent}` | {len(failing)}: {', '.join(f'`{s}`' for s in failing) or 'none'} | "
            f"{len(passing)}: {', '.join(f'`{s}`' for s in passing) or 'none'} | "
            f"{len(comparison.by_status(UnitStatus.NOT_COMPARABLE))} | "
            f"p = {paired.p_value:.3g} over {paired.units} scenarios "
            f"({'significant' if paired.significant else 'not significant'} at alpha = 0.05) |"
        )
    lines += [
        "",
        "## Limitations and sources of uncertainty",
        "",
        "- **Synthetic and tiny.** Five fictional cases and 16 scenarios; results say nothing "
        "about real-world research tasks or real language models.",
        "- **Repetitions are not independent samples.** The agents are deterministic and every "
        "fault fires with probability 1, so repetitions of a scenario give identical results. The "
        "effective sample size is the number of scenarios (16), not the number of runs; run-level "
        "intervals above treat runs as independent and are therefore too narrow.",
        "- **Low statistical power.** With 16 paired scenarios a one-directional change needs at "
        "least 6 discordant scenarios to reach p < 0.05; smaller regressions are flagged by the "
        "zero-tolerance policy, not by significance.",
        "- **Virtual time.** Latency is measured on the runner's manual clock (injected delays and "
        "back-off), not wall-clock performance.",
        "- **Cost is trivially zero.** The deterministic agent makes no model calls; cost is a "
        "known zero, not an estimate for LLM agents.",
        "- **Evaluator limits.** Text-matching criteria cannot tell an assertion from a quotation; "
        "no rubric/LLM judging and no human labels were used, so evaluator accuracy is unmeasured "
        "(see Milestone 8).",
        "- **Expectations encode one view of correct behaviour.** E.g. the misleading-output "
        "scenario expects an answer (two sources remain consistent); the reference agent reports a "
        "conflict instead and fails it. That is a documented, intentional controlled failure.",
        "- Dataset card with case-level detail: `docs/benchmarks/reliability-demo-1.0.0.md`.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--suite", required=True)
    parser.add_argument("--agents", default="baseline,no-retry,single-source")
    parser.add_argument("--repetitions", type=int, default=2)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    suite = _suite(args.suite)
    agents = [a.strip() for a in args.agents.split(",") if a.strip()]
    unknown = [a for a in agents if a not in AGENTS]
    if unknown:
        parser.error(f"unknown agents: {', '.join(unknown)}")
    results = {
        agent: run_sample_experiment(
            f"report-{agent}",
            sample_configuration(AGENTS[agent], suite=suite, repetitions=args.repetitions),
            suite=suite,
        )
        for agent in agents
    }
    command = (
        f"uv run python -m app.benchmarks.report --suite {args.suite} --agents {','.join(agents)} "
        f"--repetitions {args.repetitions} --output {args.output}"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(suite, results, args.repetitions, command), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
